//! On-disk wallpaper library: user-imported items, each a Lively project folder.
//!
//! Every path that originates from user input (a file they picked, a title they
//! typed) is sanitised before it reaches the filesystem. The threat is mundane
//! but real: a wallpaper named `../../../Library/LaunchAgents/evil.plist`
//! imported through the library would otherwise escape the library directory.

use std::fs;
use std::path::{Path, PathBuf};

use crate::config::LivelyConfig;
use crate::engine::{renderer_for_extension, Renderer};
use crate::error::{Error, Result};
use crate::package::LivelyInfo;

// Generated by build.rs: the wallpaper collection compiled into the binary.
include!(concat!(env!("OUT_DIR"), "/builtin_wallpapers.rs"));

// `author`, `desc` and `thumbnail_path` are part of the library record that a
// settings UI will consume; the CLI prints only id/type/size/title today.
#[allow(dead_code)]
#[derive(Debug, Clone)]
pub struct LibraryItem {
    pub id: String,
    pub title: String,
    pub author: String,
    pub license: String,
    pub desc: String,
    pub wallpaper_type: i32,
    pub path: PathBuf,
    pub thumbnail_path: Option<PathBuf>,
}

/// Stamp file written into each seeded built-in, so seeding is idempotent.
const BUILTIN_STAMP: &str = ".lively-builtin";

/// Bump to refresh every built-in wallpaper on the next launch.
const BUILTIN_VERSION: &str = "2";

/// Largest media file we will copy into the library. Anything bigger is almost
/// certainly a mistake, and copying it would block the daemon.
const MAX_IMPORT_BYTES: u64 = 4 * 1024 * 1024 * 1024;

#[derive(Debug)]
pub struct LibraryManager {
    pub library_dir: PathBuf,
    pub items: Vec<LibraryItem>,
}

impl LibraryManager {
    pub fn new() -> Result<Self> {
        let library_dir = LivelyConfig::support_dir().join("Library");
        fs::create_dir_all(&library_dir).map_err(|e| Error::io(&library_dir, e))?;

        let mut mgr = Self {
            library_dir,
            items: Vec::new(),
        };
        // Seed before the first scan so the built-ins are part of it.
        mgr.seed_builtins();
        mgr.reload();
        Ok(mgr)
    }

    /// Write the wallpapers compiled into the binary into the library.
    ///
    /// Runs on every start but is a no-op after the first: each item carries a
    /// stamp of the version it was written from, and nothing is copied unless
    /// that stamp is missing or older. App updates therefore cost nothing,
    /// while a shipped wallpaper that was later corrected can still be fixed.
    fn seed_builtins(&mut self) {
        for (name, files) in BUILTIN_WALLPAPERS {
            let target_dir = self.library_dir.join(name);
            let stamp_path = target_dir.join(BUILTIN_STAMP);

            if let Ok(stamp) = fs::read_to_string(&stamp_path) {
                if stamp.trim() == BUILTIN_VERSION {
                    continue;
                }
                // Written by an older build: replace in place, so a wallpaper
                // already applied keeps working.
                if let Err(e) = fs::remove_dir_all(&target_dir) {
                    log::warn!("could not refresh built-in wallpaper {name}: {e}");
                    continue;
                }
            }

            if let Err(e) = write_builtin_wallpaper(&target_dir, files) {
                log::warn!("could not install built-in wallpaper {name}: {e}");
                let _ = fs::remove_dir_all(&target_dir);
            }
        }
    }

    /// Whether an item ships with the app rather than being user-imported.
    pub fn is_builtin(id: &str) -> bool {
        BUILTIN_WALLPAPERS.iter().any(|(name, _)| *name == id)
    }

    /// Point the manager at a specific directory. Used by tests, and by
    /// alternate library locations later.
    #[allow(dead_code)]
    pub fn with_dir(library_dir: impl Into<PathBuf>) -> Result<Self> {
        let library_dir = library_dir.into();
        fs::create_dir_all(&library_dir).map_err(|e| Error::io(&library_dir, e))?;
        let mut mgr = Self {
            library_dir,
            items: Vec::new(),
        };
        mgr.reload();
        Ok(mgr)
    }

    /// Rescan the library folder. A single bad item is skipped, not fatal:
    /// one corrupt folder must not hide the other 200 wallpapers.
    pub fn reload(&mut self) {
        self.items.clear();

        let entries = match fs::read_dir(&self.library_dir) {
            Ok(e) => e,
            Err(e) => {
                log::warn!("cannot read library at {}: {e}", self.library_dir.display());
                return;
            }
        };

        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_dir() || !path.join("LivelyInfo.json").exists() {
                continue;
            }

            match LivelyInfo::load_from_dir(&path) {
                Ok(info) => {
                    let id = path
                        .file_name()
                        .and_then(|s| s.to_str())
                        .unwrap_or("item")
                        .to_string();
                    let thumb = info
                        .thumbnail
                        .as_ref()
                        .filter(|t| !t.contains(".."))
                        .map(|t| path.join(t));

                    self.items.push(LibraryItem {
                        id,
                        title: info.title,
                        author: info.author.unwrap_or_default(),
                        license: info.license.unwrap_or_default(),
                        desc: info.desc.unwrap_or_default(),
                        wallpaper_type: info.wallpaper_type,
                        path,
                        thumbnail_path: thumb,
                    });
                }
                Err(e) => log::warn!(
                    "skipping unreadable library item at {}: {e}",
                    path.display()
                ),
            }
        }

        self.items.sort_by_key(|item| item.title.to_lowercase());
    }

    /// Look up an item by id.
    #[allow(dead_code)]
    pub fn find(&self, id: &str) -> Option<&LibraryItem> {
        self.items.iter().find(|i| i.id == id)
    }

    /// Import a media file or an existing Lively project directory.
    pub fn add_from_media(&mut self, source: &Path) -> Result<LibraryItem> {
        if !source.exists() {
            return Err(Error::PathNotFound(source.to_path_buf()));
        }

        if source.is_dir() {
            return self.import_project(source);
        }

        let meta = fs::metadata(source).map_err(|e| Error::io(source, e))?;
        if meta.len() > MAX_IMPORT_BYTES {
            return Err(Error::Invalid(format!(
                "file is too large to import ({} MB limit)",
                MAX_IMPORT_BYTES / (1024 * 1024)
            )));
        }

        let ext = source
            .extension()
            .and_then(|e| e.to_str())
            .ok_or_else(|| Error::Invalid(format!("{} has no file extension", source.display())))?
            .to_string();

        // Validate before copying so we never import something we cannot render.
        let renderer = renderer_for_extension(&ext)?;
        let wallpaper_type = type_code_for_renderer(renderer);

        // Two different names, for two different jobs:
        //   * `display_title` is what the user reads — keep the original spaces
        //   * `safe_stem` is a directory name — must not contain separators
        // Using the sanitised form for both is why "My Video.mp4" used to appear
        // in the library as "My_Video".
        let display_title = source
            .file_stem()
            .and_then(|s| s.to_str())
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .unwrap_or("Wallpaper")
            .to_string();

        let safe_stem = sanitize_component(&display_title);
        let safe_file = sanitize_component(
            source
                .file_name()
                .and_then(|s| s.to_str())
                .unwrap_or("media"),
        );

        let item_id = unique_id(&safe_stem);
        let target_dir = self.library_dir.join(&item_id);
        fs::create_dir_all(&target_dir).map_err(|e| Error::io(&target_dir, e))?;

        let dest_file = target_dir.join(&safe_file);
        fs::copy(source, &dest_file).map_err(|e| Error::io(&dest_file, e))?;

        let info = LivelyInfo {
            app_version: "2.0.0.0".to_string(),
            title: display_title,
            thumbnail: None,
            preview: None,
            desc: Some(import_description(renderer, meta.len())),
            author: Some("Local".to_string()),
            license: None,
            contact: None,
            wallpaper_type,
            file_name: safe_file,
            arguments: None,
            root_folder: target_dir.clone(),
        };

        let json = serde_json::to_vec_pretty(&info)?;
        fs::write(target_dir.join("LivelyInfo.json"), json)
            .map_err(|e| Error::io(target_dir.join("LivelyInfo.json"), e))?;

        let item = LibraryItem {
            id: item_id,
            title: info.title,
            author: info.author.unwrap_or_default(),
            license: info.license.unwrap_or_default(),
            desc: info.desc.unwrap_or_default(),
            wallpaper_type,
            path: target_dir,
            thumbnail_path: None,
        };

        self.items.push(item.clone());
        self.sort_items();
        Ok(item)
    }

    /// Register an existing Lively project by copying it into the library.
    fn import_project(&mut self, source: &Path) -> Result<LibraryItem> {
        let info_path = source.join("LivelyInfo.json");
        if !info_path.exists() {
            return Err(Error::PathNotFound(info_path));
        }
        let info = LivelyInfo::load_from_dir(source).map_err(|e| Error::Invalid(e.to_string()))?;
        let media = info.target_path();
        if !media.exists() {
            return Err(Error::PathNotFound(media));
        }

        let stem = sanitize_component(&info.title);
        let item_id = unique_id(&stem);
        let target_dir = self.library_dir.join(&item_id);
        copy_dir_recursive(source, &target_dir)?;

        let item = LibraryItem {
            id: item_id,
            title: info.title,
            author: info.author.unwrap_or_default(),
            license: info.license.unwrap_or_default(),
            desc: info.desc.unwrap_or_default(),
            wallpaper_type: info.wallpaper_type,
            path: target_dir,
            thumbnail_path: None,
        };
        self.items.push(item.clone());
        self.sort_items();
        Ok(item)
    }

    /// Delete a library item and its folder.
    ///
    /// Built-in wallpapers are refused: they are reinstalled on the next
    /// launch, so deleting one would look like it worked and then reappear.
    pub fn remove(&mut self, id: &str) -> Result<()> {
        let index = self
            .items
            .iter()
            .position(|i| i.id == id)
            .ok_or_else(|| Error::Invalid(format!("no library item with id {id}")))?;

        if Self::is_builtin(id) {
            return Err(Error::Invalid(format!(
                "`{id}` ships with Lively and cannot be removed"
            )));
        }

        let item = self.items.remove(index);

        // Defence in depth: only ever delete inside the library root.
        if !item.path.starts_with(&self.library_dir) {
            return Err(Error::Invalid(
                "refusing to delete outside the library".into(),
            ));
        }
        if item.path.exists() {
            fs::remove_dir_all(&item.path).map_err(|e| Error::io(&item.path, e))?;
        }
        Ok(())
    }

    fn sort_items(&mut self) {
        self.items.sort_by_key(|item| item.title.to_lowercase());
    }
}

/// A one-line description for an imported file.
///
/// The renderer is worth stating plainly — "Video" tells the user what will
/// actually happen, where "Imported .mp4" only restates the extension.
fn import_description(renderer: Renderer, bytes: u64) -> String {
    let kind = match renderer {
        Renderer::Video => "Video wallpaper",
        Renderer::WebFile => "Web wallpaper",
        Renderer::WebUrl => "Web wallpaper",
        Renderer::Shader => "Metal shader wallpaper",
        Renderer::Image => "Image wallpaper",
    };
    format!("{kind} · {}", human_bytes(bytes))
}

fn human_bytes(bytes: u64) -> String {
    const UNITS: [&str; 3] = ["KB", "MB", "GB"];
    let mut size = bytes as f64;
    let mut unit = 0;
    while size >= 1024.0 && unit + 1 < UNITS.len() {
        size /= 1024.0;
        unit += 1;
    }
    if unit == 0 {
        format!("{bytes} B")
    } else {
        format!("{size:.1} {}", UNITS[unit])
    }
}

/// Materialise one embedded wallpaper into the library folder.
fn write_builtin_wallpaper(target: &Path, files: &[(&str, &[u8])]) -> Result<()> {
    fs::create_dir_all(target).map_err(|e| Error::io(target, e))?;

    for (name, bytes) in files {
        // Names come from our own embedded table, but validate anyway: this
        // writes to disk and must not be the weak link.
        let safe = sanitize_component(name);
        let path = target.join(&safe);
        fs::write(&path, bytes).map_err(|e| Error::io(&path, e))?;
    }

    let stamp = target.join(BUILTIN_STAMP);
    fs::write(&stamp, BUILTIN_VERSION).map_err(|e| Error::io(&stamp, e))?;
    Ok(())
}

fn type_code_for_renderer(renderer: Renderer) -> i32 {
    match renderer {
        Renderer::Video => 0,
        Renderer::WebFile | Renderer::WebUrl => 1,
        Renderer::Image => 5,
        Renderer::Shader => 6,
    }
}

/// Reduce `s` to a single safe path component.
///
/// Strips directory separators and `..`, replaces anything outside
/// `[A-Za-z0-9._-]` with `_`, and bounds the length. Guarantees the result
/// contains no `/`, is not `.` or `..`, and is not empty.
pub fn sanitize_component(s: &str) -> String {
    let cleaned: String = s
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') {
                c
            } else {
                '_'
            }
        })
        .collect();

    // Strip leading dots so we cannot produce a hidden file or "..".
    let trimmed = cleaned.trim_start_matches('.').to_string();
    let mut out: String = trimmed.chars().take(64).collect();

    while out.ends_with(['.', ' ']) {
        out.pop();
    }

    if out.is_empty() {
        "wallpaper".to_string()
    } else {
        out
    }
}

/// Build a collision-resistant, filesystem-safe item id.
fn unique_id(stem: &str) -> String {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let pid = std::process::id();
    format!("{stem}_{pid}_{:x}", nanos)
}

/// Recursively copy a directory, refusing to follow symlinks out of the source.
fn copy_dir_recursive(src: &Path, dst: &Path) -> Result<()> {
    fs::create_dir_all(dst).map_err(|e| Error::io(dst, e))?;

    for entry in fs::read_dir(src).map_err(|e| Error::io(src, e))?.flatten() {
        let from = entry.path();
        let name = entry.file_name();
        let to = dst.join(&name);

        let meta = fs::symlink_metadata(&from).map_err(|e| Error::io(&from, e))?;

        if meta.file_type().is_symlink() {
            log::warn!("skipping symlink while importing: {}", from.display());
            continue;
        }

        if meta.is_dir() {
            copy_dir_recursive(&from, &to)?;
        } else if meta.is_file() {
            fs::copy(&from, &to).map_err(|e| Error::io(&to, e))?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmpdir(tag: &str) -> PathBuf {
        let p = std::env::temp_dir().join(format!("lively-lib-{tag}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&p);
        fs::create_dir_all(&p).unwrap();
        p
    }

    #[test]
    fn sanitize_strips_path_traversal() {
        // The guarantee that matters is "one safe component": no separator, and
        // joining it onto a directory cannot escape that directory.
        let base = PathBuf::from("/library");
        for hostile in [
            "../../../etc/passwd",
            "..",
            "a/b/c",
            "/absolute/path",
            "..\\windows\\system32",
        ] {
            let out = sanitize_component(hostile);
            assert!(!out.contains('/'), "separator survived in {out:?}");
            assert!(!out.contains('\\'), "backslash survived in {out:?}");
            assert_ne!(out, ".", "must not become the current dir");
            assert_ne!(out, "..", "must not become the parent dir");

            let joined = base.join(&out);
            assert_eq!(
                joined.parent(),
                Some(base.as_path()),
                "{out:?} escaped the base"
            );
        }
    }

    #[test]
    fn sanitize_removes_hidden_and_special_names() {
        assert_eq!(sanitize_component(".hidden"), "hidden");
        assert_eq!(sanitize_component(".."), "wallpaper");
        assert_eq!(sanitize_component(""), "wallpaper");
        assert_eq!(sanitize_component("..."), "wallpaper");
    }

    #[test]
    fn sanitize_replaces_shell_metacharacters() {
        // Every character outside [A-Za-z0-9._-] becomes an underscore.
        let out = sanitize_component("my;rm -rf wallpaper$(whoami)");
        assert_eq!(out, "my_rm_-rf_wallpaper__whoami_");
        assert!(!out.contains(';'), "got {out}");
        assert!(!out.contains('$'), "got {out}");
    }

    #[test]
    fn sanitize_bounds_length() {
        let out = sanitize_component(&"a".repeat(500));
        assert_eq!(out.len(), 64);
    }

    #[test]
    fn sanitize_keeps_safe_characters_intact() {
        assert_eq!(sanitize_component("My_Wallpaper-01"), "My_Wallpaper-01");
    }

    #[test]
    fn empty_library_starts_empty() {
        let dir = tmpdir("empty");
        let lib = LibraryManager::with_dir(&dir).unwrap();
        assert!(lib.items.is_empty());
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn importing_a_video_creates_a_package() {
        let dir = tmpdir("import-video");
        let src = dir.join("My Clip.mp4");
        fs::write(&src, b"fake video data").unwrap();

        let lib_dir = dir.join("store");
        let mut lib = LibraryManager::with_dir(&lib_dir).unwrap();
        let item = lib.add_from_media(&src).unwrap();

        assert_eq!(item.wallpaper_type, 0);
        assert!(item.path.join("LivelyInfo.json").exists());
        assert_eq!(lib.items.len(), 1);

        // The media file kept its extension so the renderer can find it.
        assert!(item.path.join("My_Clip.mp4").exists());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn importing_an_unsupported_file_is_rejected_before_copying() {
        let dir = tmpdir("import-bad");
        let src = dir.join("notes.txt");
        fs::write(&src, b"hello").unwrap();

        let lib_dir = dir.join("store");
        let mut lib = LibraryManager::with_dir(&lib_dir).unwrap();
        assert!(lib.add_from_media(&src).is_err());
        assert!(lib.items.is_empty(), "nothing should have been imported");

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn importing_a_missing_file_is_rejected() {
        let dir = tmpdir("import-missing");
        let mut lib = LibraryManager::with_dir(dir.join("store")).unwrap();
        let err = lib.add_from_media(&dir.join("nope.mp4")).unwrap_err();
        assert!(matches!(err, Error::PathNotFound(_)));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn hostile_filename_cannot_escape_the_library() {
        let dir = tmpdir("import-evil");
        // A file literally named with traversal segments.
        let src = dir.join("..").join("..").join("evil.mp4");
        fs::create_dir_all(src.parent().unwrap()).unwrap();
        fs::write(&src, b"x").unwrap();

        let lib_dir = dir.join("store");
        let mut lib = LibraryManager::with_dir(&lib_dir).unwrap();
        let item = lib.add_from_media(&src).unwrap();

        // Whatever happened, the result must stay inside the library root.
        assert!(
            item.path.starts_with(&lib_dir),
            "import escaped the library: {}",
            item.path.display()
        );

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn reload_picks_up_packages_on_disk() {
        let dir = tmpdir("reload");
        let lib_dir = dir.join("store");
        let mut lib = LibraryManager::with_dir(&lib_dir).unwrap();
        assert!(lib.items.is_empty());

        // Hand-write a package folder.
        let pkg = lib_dir.join("manual");
        fs::create_dir_all(&pkg).unwrap();
        fs::write(pkg.join("a.png"), b"x").unwrap();
        fs::write(
            pkg.join("LivelyInfo.json"),
            br#"{"Title":"Manual","Type":5,"FileName":"a.png"}"#,
        )
        .unwrap();

        lib.reload();
        assert_eq!(lib.items.len(), 1);
        assert_eq!(lib.items[0].title, "Manual");
        assert!(lib.find("manual").is_some());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn reload_skips_corrupt_packages_without_failing() {
        let dir = tmpdir("reload-corrupt");
        let lib_dir = dir.join("store");

        let good = lib_dir.join("good");
        fs::create_dir_all(&good).unwrap();
        fs::write(good.join("a.png"), b"x").unwrap();
        fs::write(
            good.join("LivelyInfo.json"),
            br#"{"Title":"Good","Type":5,"FileName":"a.png"}"#,
        )
        .unwrap();

        let bad = lib_dir.join("bad");
        fs::create_dir_all(&bad).unwrap();
        fs::write(bad.join("LivelyInfo.json"), b"{ broken").unwrap();

        let lib = LibraryManager::with_dir(&lib_dir).unwrap();
        assert_eq!(lib.items.len(), 1, "the good item must survive");
        assert_eq!(lib.items[0].title, "Good");

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn items_are_sorted_case_insensitively() {
        let dir = tmpdir("sort");
        let lib_dir = dir.join("store");

        for (name, title) in [("z", "Zebra"), ("a", "apple"), ("m", "Mango")] {
            let pkg = lib_dir.join(name);
            fs::create_dir_all(&pkg).unwrap();
            fs::write(pkg.join("a.png"), b"x").unwrap();
            fs::write(
                pkg.join("LivelyInfo.json"),
                format!(r#"{{"Title":"{title}","Type":5,"FileName":"a.png"}}"#).as_bytes(),
            )
            .unwrap();
        }

        let lib = LibraryManager::with_dir(&lib_dir).unwrap();
        let titles: Vec<&str> = lib.items.iter().map(|i| i.title.as_str()).collect();
        assert_eq!(titles, vec!["apple", "Mango", "Zebra"]);

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn removing_an_item_deletes_its_folder() {
        let dir = tmpdir("remove");
        let src = dir.join("clip.mp4");
        fs::write(&src, b"x").unwrap();

        let lib_dir = dir.join("store");
        let mut lib = LibraryManager::with_dir(&lib_dir).unwrap();
        let item = lib.add_from_media(&src).unwrap();
        assert!(item.path.exists());

        lib.remove(&item.id).unwrap();
        assert!(!item.path.exists());
        assert!(lib.items.is_empty());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn removing_an_unknown_item_errors() {
        let dir = tmpdir("remove-missing");
        let mut lib = LibraryManager::with_dir(dir.join("store")).unwrap();
        assert!(lib.remove("does-not-exist").is_err());
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn thumbnail_paths_cannot_escape_via_traversal() {
        let dir = tmpdir("thumb");
        let lib_dir = dir.join("store");
        let pkg = lib_dir.join("evil-thumb");
        fs::create_dir_all(&pkg).unwrap();
        fs::write(pkg.join("a.png"), b"x").unwrap();
        fs::write(
            pkg.join("LivelyInfo.json"),
            br#"{"Title":"Evil","Type":5,"FileName":"a.png","Thumbnail":"../../../../etc/passwd"}"#,
        )
        .unwrap();

        let lib = LibraryManager::with_dir(&lib_dir).unwrap();
        assert!(
            lib.items[0].thumbnail_path.is_none(),
            "traversal thumbnail must be discarded"
        );

        let _ = fs::remove_dir_all(&dir);
    }
}
